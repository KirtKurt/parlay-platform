import {readFileSync} from 'node:fs';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const page=read('app/arbitrage-v2/page.tsx');
const calc=read('app/arbitrage-v2/calculator/page.tsx');
const historyRoute=read('app/v1/inqsi/arbitrage/history/route.ts');
const liveRoute=read('app/v1/inqsi/arbitrage/opportunities/route.ts');
const vercel=read('vercel.json');
const must=(ok,msg)=>{if(!ok)throw new Error(msg)};
must(page.includes('NO SAMPLE OPPORTUNITIES ARE BEING SHOWN'),'live fail-closed warning missing');
must(page.includes('selected.legs.map'),'multi-leg rendering missing');
must(page.includes('known sportsbook limit')||page.includes('sportsbook limit'),'limit warning missing');
must(page.includes("window.innerWidth<=980"),'mobile selection handoff missing');
must(calc.includes("setCount(3)")&&calc.includes('3-way'),'three-way calculator missing');
must(historyRoute.includes('AbortController')&&historyRoute.includes('8000'),'bounded history proxy timeout missing');
must(liveRoute.includes('AbortController')&&liveRoute.includes('20000'),'bounded live ARB proxy timeout missing');
must(liveRoute.includes("sport: incoming.get('sport') || 'all'")&&liveRoute.includes("markets: incoming.get('markets') || 'h2h,spreads,totals'"),'live ARB scan contract missing');
const cfg=JSON.parse(vercel);must(cfg.framework==='nextjs','Vercel Next.js framework config missing');
console.log('ARB prototype contract checks passed');
